func TestOutputParsesAndSignsVerifiableTokens(t *testing.T) {
	t.Parallel()
	var buf bytes.Buffer
	if err := run(&buf, time.Date(2026, 10, 11, 23, 0, 0, 0, time.FixedZone("ICT", 7*3600))); err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimSuffix(buf.String(), "\n"), "\n")
	if len(lines) != 3 {
		t.Fatalf("got %d lines, want 3:\n%s", len(lines), buf.String())
	}
	env := map[string]string{}
	for i, name := range []string{"JWT_SIGNING_KID", "JWT_SIGNING_KEY", "JWT_VERIFY_KEYS"} {
		k, v, ok := strings.Cut(lines[i], "=")
		if !ok || k != name || v == "" {
			t.Fatalf("line %d = %q, want %s=<value>", i+1, lines[i], name)
		}
		env[k] = v
	}

	kid := env["JWT_SIGNING_KID"]
	if !strings.HasPrefix(kid, "20261011-") || len(kid) != len("20261011-")+8 {
		t.Errorf("kid = %q, want 20261011-<8 hex> (UTC date)", kid)
	}
	key, err := authtoken.ParseSigningKey(kid, env["JWT_SIGNING_KEY"])
	if err != nil {
		t.Fatalf("ParseSigningKey() = %v", err)
	}
	keys, err := authtoken.ParseVerifyKeys(env["JWT_VERIFY_KEYS"])
	if err != nil {
		t.Fatalf("ParseVerifyKeys() = %v", err)
	}
	if _, ok := keys[kid]; !ok || len(keys) != 1 {
		t.Fatalf("verify keys = %v, want only kid %q", keys, kid)
	}

	userID := ids.New()
	tok, _, err := authtoken.NewIssuer(kid, key).Issue(userID)
	if err != nil {
		t.Fatal(err)
	}
	got, err := authtoken.NewVerifier(keys).Verify(tok.Reveal())
	if err != nil || got != userID {
		t.Errorf("Verify() = (%q, %v), want (%q, nil)", got, err, userID)
	}
}

func TestEachRunMakesANewKey(t *testing.T) {
	t.Parallel()
	var a, b bytes.Buffer
	now := time.Now()
	if err := run(&a, now); err != nil {
		t.Fatal(err)
	}
	if err := run(&b, now); err != nil {
		t.Fatal(err)
	}
	if a.String() == b.String() {
		t.Error("two runs printed the same key")
	}
}

// newPair returns the three lines of a new key pair and its kid, seed and public key values.
func newPair(t *testing.T) (lines, kid, seed, pub string) {
	t.Helper()
	var buf bytes.Buffer
	if err := run(&buf, time.Now()); err != nil {
		t.Fatal(err)
	}
	for l := range strings.SplitSeq(strings.TrimSuffix(buf.String(), "\n"), "\n") {
		k, v, _ := strings.Cut(l, "=")
		switch k {
		case "JWT_SIGNING_KID":
			kid = v
		case "JWT_SIGNING_KEY":
			seed = v
		case "JWT_VERIFY_KEYS":
			_, pub, _ = strings.Cut(v, ":")
		}
	}
	return buf.String(), kid, seed, pub
}

// rotation is a directory with an env file whose JWT lines sit among lines the rotation must
// leave alone, byte for byte: a comment, blank lines, other variables, no newline at the end.
type rotation struct {
	t        *testing.T
	dir, env string
	kid      string
	secrets  []string // every key value written so far, to check that none is printed
	out      bytes.Buffer
}

const (
	envHead = "# Generated by make env. Local secrets: do not commit, do not share.\nSVP_A=1\n\n"
	envMid  = "  \t\nSVP_B='two'\n"
	envTail = "SVP_C=3"
)

func newRotation(t *testing.T) *rotation {
	t.Helper()
	r := &rotation{t: t, dir: t.TempDir()}
	r.env = filepath.Join(r.dir, ".env")
	_, kid, seed, pub := newPair(t)
	r.kid = kid
	r.secrets = append(r.secrets, seed, pub)
	r.write("JWT_SIGNING_KID=" + kid + "\nJWT_SIGNING_KEY=" + seed + "\n" + envMid + "JWT_VERIFY_KEYS=" + kid + ":" + pub + "\n")
	return r
}

// write sets the env file to envHead, jwt (the JWT lines, envMid between them) and envTail.
func (r *rotation) write(jwt string) {
	r.t.Helper()
	if err := os.WriteFile(r.env, []byte(envHead+jwt+envTail), 0o600); err != nil {
		r.t.Fatal(err)
	}
}

func (r *rotation) step(step string) error {
	return rotate(&r.out, step, r.env, time.Now())
}

func (r *rotation) mustStep(step string) {
	r.t.Helper()
	if err := r.step(step); err != nil {
		r.t.Fatalf("rotate %s: %v", step, err)
	}
	r.checkFile(r.env)
	if p := r.pending(); p != nil {
		r.secrets = append(r.secrets, p["JWT_SIGNING_KEY"], strings.SplitN(p["JWT_VERIFY_KEYS"], ":", 2)[1])
	}
}

// vars reads the JWT variables of path and checks that every other line is as written.
func (r *rotation) vars() map[string]string {
	r.t.Helper()
	data, err := os.ReadFile(r.env)
	if err != nil {
		r.t.Fatal(err)
	}
	s := string(data)
	vars := map[string]string{}
	var rest strings.Builder
	for l := range strings.SplitSeq(s, "\n") {
		if k, v, ok := strings.Cut(l, "="); ok && strings.HasPrefix(k, "JWT_") {
			vars[k] = v
			continue
		}
		rest.WriteString(l + "\n")
	}
	if want := envHead + envMid + envTail + "\n"; rest.String() != want {
		r.t.Errorf("lines other than JWT_* = %q, want %q", rest.String(), want)
	}
	return vars
}

// pending returns the pending key's variables, nil when the file does not exist.
func (r *rotation) pending() map[string]string {
	r.t.Helper()
	path := filepath.Join(r.dir, ".env.jwt-next")
	data, err := os.ReadFile(path) // #nosec G304 -- a file in the test's temporary directory.
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		r.t.Fatal(err)
	}
	r.checkFile(path)
	vars := map[string]string{}
	for l := range strings.SplitSeq(strings.TrimSuffix(string(data), "\n"), "\n") {
		k, v, _ := strings.Cut(l, "=")
		vars[k] = v
	}
	return vars
}

// checkFile checks that path has mode 600 and that no temporary file is left beside it.
func (r *rotation) checkFile(path string) {
	r.t.Helper()
	info, err := os.Stat(path)
	if err != nil {
		r.t.Fatal(err)
	}
	if info.Mode().Perm() != 0o600 {
		r.t.Errorf("%s mode = %v, want 0600", path, info.Mode().Perm())
	}
	tmp, _ := filepath.Glob(filepath.Join(r.dir, "*.tmp.*"))
	if len(tmp) > 0 {
		r.t.Errorf("temporary files left: %v", tmp)
	}
}

// noLeak fails when text holds any key value written so far.
func (r *rotation) noLeak(what, text string) {
	r.t.Helper()
	for _, s := range r.secrets {
		if strings.Contains(text, s) {
			r.t.Errorf("%s holds a key value:\n%s", what, text)
		}
	}
}

func TestRotateAddSignDrop(t *testing.T) {
	t.Parallel()
	r := newRotation(t)
	oldKID := r.kid
	before := r.vars()

	r.mustStep("add")
	p := r.pending()
	if p == nil || len(p) != 3 {
		t.Fatalf("pending key = %v, want its three variables", p)
	}
	newKID := p["JWT_SIGNING_KID"]
	got := r.vars()
	if want := before["JWT_VERIFY_KEYS"] + "," + p["JWT_VERIFY_KEYS"]; got["JWT_VERIFY_KEYS"] != want {
		t.Errorf("add: JWT_VERIFY_KEYS has not the new key appended")
	}
	if got["JWT_SIGNING_KID"] != oldKID || got["JWT_SIGNING_KEY"] != before["JWT_SIGNING_KEY"] {
		t.Errorf("add changed the signing key")
	}
	if !strings.Contains(r.out.String(), newKID) || !strings.Contains(r.out.String(), "make jwt-rotate STEP=sign") {
		t.Errorf("add printed %q, want the new kid and the next step", r.out.String())
	}

	r.mustStep("sign")
	got = r.vars()
	if got["JWT_SIGNING_KID"] != newKID || got["JWT_SIGNING_KEY"] != p["JWT_SIGNING_KEY"] {
		t.Errorf("sign: signing key is not the pending one")
	}
	key, err := authtoken.ParseSigningKey(got["JWT_SIGNING_KID"], got["JWT_SIGNING_KEY"])
	if err != nil {
		t.Fatal(err)
	}
	keys, err := authtoken.ParseVerifyKeys(got["JWT_VERIFY_KEYS"])
	if err != nil {
		t.Fatal(err)
	}
	userID := ids.New()
	tok, _, err := authtoken.NewIssuer(newKID, key).Issue(userID)
	if err != nil {
		t.Fatal(err)
	}
	if id, err := authtoken.NewVerifier(keys).Verify(tok.Reveal()); err != nil || id != userID {
		t.Errorf("token of the new signing key: Verify() = (%q, %v)", id, err)
	}

	r.mustStep("drop")
	got = r.vars()
	if got["JWT_VERIFY_KEYS"] != p["JWT_VERIFY_KEYS"] {
		t.Errorf("drop: JWT_VERIFY_KEYS is not only the new key")
	}
	if r.pending() != nil {
		t.Error("drop left the pending key")
	}
	for _, kid := range []string{oldKID, newKID} {
		if !strings.Contains(r.out.String(), kid) {
			t.Errorf("output lacks kid %s", kid)
		}
	}
	r.noLeak("stdout", r.out.String())

	// A second rotation starts from the state the first left.
	r.mustStep("add")
	r.mustStep("sign")
	r.mustStep("drop")
	if keys, err := authtoken.ParseVerifyKeys(r.vars()["JWT_VERIFY_KEYS"]); err != nil || len(keys) != 1 {
		t.Errorf("after two rotations: %d verify keys, err %v; want 1", len(keys), err)
	}
	r.noLeak("stdout", r.out.String())
}

// TestRotateOutOfOrder runs each step where the runbook does not allow it: the step fails and
// leaves both files as they were.
func TestRotateOutOfOrder(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name  string
		setup []string
		edit  func(r *rotation)
		step  string
		want  string
	}{
		{name: "add twice", setup: []string{"add"}, step: "add", want: "rotation is under way"},
		{name: "add after sign", setup: []string{"add", "sign"}, step: "add", want: "rotation is under way"},
		{name: "sign with no pending key", step: "sign", want: "no rotation under way"},
		{name: "sign twice", setup: []string{"add", "sign"}, step: "sign", want: "is already"},
		{name: "drop with no pending key", step: "drop", want: "no rotation under way"},
		{name: "drop before sign", setup: []string{"add"}, step: "drop", want: "STEP=sign first"},
		{name: "sign with pending kid not verified", setup: []string{"add"}, step: "sign", want: "lacks the verify key",
			edit: func(r *rotation) {
				v := r.vars()
				first, _, _ := strings.Cut(v["JWT_VERIFY_KEYS"], ",")
				r.write("JWT_SIGNING_KID=" + v["JWT_SIGNING_KID"] + "\nJWT_SIGNING_KEY=" + v["JWT_SIGNING_KEY"] + "\n" +
					envMid + "JWT_VERIFY_KEYS=" + first + "\n")
			}},
		{name: "sign with another key under the pending kid", setup: []string{"add"}, step: "sign",
			want: "lacks the verify key", edit: func(r *rotation) {
				v := r.vars()
				first, _, _ := strings.Cut(v["JWT_VERIFY_KEYS"], ",")
				_, _, _, other := newPair(r.t)
				r.secrets = append(r.secrets, other)
				r.write("JWT_SIGNING_KID=" + v["JWT_SIGNING_KID"] + "\nJWT_SIGNING_KEY=" + v["JWT_SIGNING_KEY"] + "\n" +
					envMid + "JWT_VERIFY_KEYS=" + first + "," + r.pending()["JWT_SIGNING_KID"] + ":" + other + "\n")
			}},
		{name: "unknown step", step: "remove", want: "unknown step"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			r := newRotation(t)
			for _, s := range tc.setup {
				r.mustStep(s)
			}
			if tc.edit != nil {
				tc.edit(r)
			}
			env, pending := snapshot(t, r.env), snapshot(t, filepath.Join(r.dir, ".env.jwt-next"))
			r.out.Reset()
			err := r.step(tc.step)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("rotate %s = %v, want an error with %q", tc.step, err, tc.want)
			}
			if r.out.Len() != 0 {
				t.Errorf("printed %q on error", r.out.String())
			}
			r.noLeak("error", err.Error())
			if snapshot(t, r.env) != env || snapshot(t, filepath.Join(r.dir, ".env.jwt-next")) != pending {
				t.Error("a refused step changed a file")
			}
		})
	}
}

// TestRotateBadEnv gives each step an env file it must not read: the step fails, names the
// problem without a value and writes nothing.
func TestRotateBadEnv(t *testing.T) {
	t.Parallel()
	_, kid, seed, pub := newPair(t)
	_, kid2, _, pub2 := newPair(t)
	signing := "JWT_SIGNING_KID=" + kid + "\nJWT_SIGNING_KEY=" + seed + "\n"
	verify := "JWT_VERIFY_KEYS=" + kid + ":" + pub + "\n"
	for _, tc := range []struct{ name, jwt, want string }{
		{"no JWT_SIGNING_KID", "JWT_SIGNING_KEY=" + seed + "\n" + verify, "lacks JWT_SIGNING_KID"},
		{"no JWT_SIGNING_KEY", "JWT_SIGNING_KID=" + kid + "\n" + verify, "lacks JWT_SIGNING_KEY"},
		{"no JWT_VERIFY_KEYS", signing, "lacks JWT_VERIFY_KEYS"},
		{"empty JWT_VERIFY_KEYS", signing + "JWT_VERIFY_KEYS=\n", "lacks JWT_VERIFY_KEYS"},
		{"JWT_VERIFY_KEYS twice", signing + verify + verify, "set again"},
		{"entry without kid", signing + "JWT_VERIFY_KEYS=" + kid + ":" + pub + "," + pub2 + "\n", "entry 2 of"},
		{"entry not base64", signing + "JWT_VERIFY_KEYS=" + kid + ":" + pub + "," + kid2 + ":" + pub2[1:] + "\n",
			"entry 2 of"},
		{"empty entry", signing + "JWT_VERIFY_KEYS=" + kid + ":" + pub + ",\n", "entry 2 of"},
		{"kid twice", signing + "JWT_VERIFY_KEYS=" + kid + ":" + pub + "," + kid + ":" + pub2 + "\n", "twice"},
		{"blank in value", signing + "JWT_VERIFY_KEYS=" + kid + ":" + pub + ", " + kid2 + ":" + pub2 + "\n", "blank"},
		{"CRLF line", signing + "JWT_VERIFY_KEYS=" + kid + ":" + pub + "\r\n", "CR"},
		{"signing key not a seed", "JWT_SIGNING_KID=" + kid + "\nJWT_SIGNING_KEY=" + pub2 + "x\n" + verify,
			"not a kid and the standard base64"},
	} {
		for _, step := range []string{"add", "sign", "drop"} {
			t.Run(tc.name+"/"+step, func(t *testing.T) {
				t.Parallel()
				r := &rotation{t: t, dir: t.TempDir(), secrets: []string{seed, pub, pub2, pub2[1:]}}
				r.env = filepath.Join(r.dir, ".env")
				r.write(tc.jwt)
				before := snapshot(t, r.env)
				err := r.step(step)
				if err == nil || !strings.Contains(err.Error(), tc.want) {
					t.Fatalf("rotate %s = %v, want an error with %q", step, err, tc.want)
				}
				r.noLeak("error", err.Error())
				if snapshot(t, r.env) != before {
					t.Error("the env file changed")
				}
				if entries, _ := os.ReadDir(r.dir); len(entries) != 1 {
					t.Errorf("files in the directory: %v, want only .env", entries)
				}
			})
		}
	}
}

func TestRotateQuotedValues(t *testing.T) {
	t.Parallel()
	r := newRotation(t)
	v := r.vars()
	r.write(`JWT_SIGNING_KID="` + v["JWT_SIGNING_KID"] + "\"\nJWT_SIGNING_KEY='" + v["JWT_SIGNING_KEY"] + "'\n" + envMid +
		`JWT_VERIFY_KEYS="` + v["JWT_VERIFY_KEYS"] + "\"\n")
	r.mustStep("add")
	if got := r.vars()["JWT_VERIFY_KEYS"]; got != v["JWT_VERIFY_KEYS"]+","+r.pending()["JWT_VERIFY_KEYS"] {
		t.Errorf("JWT_VERIFY_KEYS = %q, want the old value unquoted with the new key appended", got)
	}
}

func snapshot(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path) // #nosec G304 -- a file in the test's temporary directory.
	if errors.Is(err, fs.ErrNotExist) {
		return "<none>"
	}
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

